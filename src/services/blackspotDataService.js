/**
 * Validates whether latitude and longitude lie within the geographic territory of India.
 * Bounds: Latitude 6.5° N to 37.5° N, Longitude 68.0° E to 97.5° E.
 */
export function validateIndiaCoordinates(lat, lon) {
  const latitude = parseFloat(lat);
  const longitude = parseFloat(lon);

  if (isNaN(latitude) || isNaN(longitude)) {
    return { isValid: false, reason: 'Coordinates must be valid decimal numbers.' };
  }

  if (latitude < 6.5 || latitude > 37.5) {
    return {
      isValid: false,
      reason: `Latitude ${latitude.toFixed(4)}° is outside India's geographic bounds (6.5° N - 37.5° N).`,
    };
  }

  if (longitude < 68.0 || longitude > 97.5) {
    return {
      isValid: false,
      reason: `Longitude ${longitude.toFixed(4)}° is outside India's geographic bounds (68.0° E - 97.5° E).`,
    };
  }

  return { isValid: true, lat: latitude, lon: longitude };
}

/**
 * Objective, data-driven empirical risk score calculation.
 * Replaces arbitrary subjective labels with documented multi-factor formula:
 * 
 * Score = min(100, (0.40 * (Fatalities / MaxFatalities) +
 *                   0.30 * (Accidents / MaxAccidents) +
 *                   0.20 * (SeverityIndex / 100) +
 *                   0.10 * RoadClassWeight) * 100)
 */
export function calculateEmpiricalRiskScore(accidents, fatalities, grievousInjuries = 0, roadClass = 'National Highway') {
  const acc = Math.max(1, Number(accidents) || 1);
  const fat = Math.max(0, Number(fatalities) || 0);

  // MoRTH Severity Index: Fatalities per 100 accidents
  const severityIndex = Math.min(100, (fat / acc) * 100);

  // Benchmarks calibrated against MoRTH 3-year blackspot criteria
  const maxAccidentRef = 65; // highest 3-year blackspot frequency reference
  const maxFatalityRef = 35; // highest 3-year blackspot fatality reference

  const normFat = Math.min(1, fat / maxFatalityRef);
  const normAcc = Math.min(1, acc / maxAccidentRef);
  const normSev = severityIndex / 100;

  let roadFactor = 0.8;
  const rc = String(roadClass).toLowerCase();
  if (rc.includes('expressway') || rc.includes('national highway') || rc.includes('nh')) {
    roadFactor = 1.0; // High speed exposure
  } else if (rc.includes('state highway') || rc.includes('sh')) {
    roadFactor = 0.85;
  } else {
    roadFactor = 0.65;
  }

  const rawScore = (0.40 * normFat + 0.30 * normAcc + 0.20 * normSev + 0.10 * roadFactor) * 100;
  const score = Math.max(15, Math.min(98, Math.round(rawScore)));

  let riskLevel = 'Moderate';
  let riskCategory = 'medium';
  if (score >= 70) {
    riskLevel = 'Severe';
    riskCategory = 'high';
  } else if (score >= 50) {
    riskLevel = 'High';
    riskCategory = 'high';
  } else if (score >= 30) {
    riskLevel = 'Moderate';
    riskCategory = 'medium';
  } else {
    riskLevel = 'Low';
    riskCategory = 'low';
  }

  return {
    score,
    riskLevel,
    riskCategory,
    severityIndex: parseFloat(severityIndex.toFixed(1)),
  };
}

