/**
 * Initialize geolocated blackspots with empirical risk scores
 */
export function getInitializedVerifiedBlackspots() {
  return VERIFIED_GEOLOCATED_BLACKSPOTS.map((bs) => {
    const risk = calculateEmpiricalRiskScore(bs.accidents, bs.fatalities, bs.grievousInjuries, bs.roadType);
    return {
      ...bs,
      riskScore: risk.score,
      riskLevel: risk.riskLevel,
      riskCategory: risk.riskCategory,
      severityIndex: risk.severityIndex,
      coordinates: `${Number(bs.lat).toFixed(4)}° N, ${Number(bs.lng).toFixed(4)}° E`,
      radiusMeters: Math.min(650, Math.max(300, bs.accidents * 12)),
      isVerifiedHistoricalRecord: true,
    };
  });
}
